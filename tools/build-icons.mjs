#!/usr/bin/env node
// @ts-check
/**
 * Build src/assets/icons/sprite.svg from src/assets/icons/icons.json.
 * Sources: node_modules/lucide-static/icons/<name>.svg (devDependency), or a local
 * override in src/assets/icons/brands/<name>.svg (brand marks Lucide doesn't ship).
 * The sprite is committed, so the site build never needs node_modules.
 *
 *   npm run icons
 */
import { readFile, writeFile, copyFile, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ICON_DIR = path.join(ROOT, 'src/assets/icons');
const LUCIDE = path.join(ROOT, 'node_modules/lucide-static');

/** @param {string} f */
const exists = (f) => access(f).then(() => true, () => false);

const { icons } = JSON.parse(await readFile(path.join(ICON_DIR, 'icons.json'), 'utf8'));
if (!(await exists(LUCIDE))) {
  console.error('✗ lucide-static not installed. Run `npm install` first.');
  process.exit(1);
}
const lucideVersion = JSON.parse(await readFile(path.join(LUCIDE, 'package.json'), 'utf8')).version;

const symbols = [];
const missing = [];
for (const name of icons) {
  const local = path.join(ICON_DIR, 'brands', `${name}.svg`);
  const fromLucide = path.join(LUCIDE, 'icons', `${name}.svg`);
  const file = (await exists(local)) ? local : (await exists(fromLucide)) ? fromLucide : null;
  if (!file) {
    missing.push(name);
    continue;
  }
  const svg = (await readFile(file, 'utf8')).replace(/<!--[\s\S]*?-->/g, '');
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 24 24';
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim();
  symbols.push(
    `  <symbol id="${name}" viewBox="${viewBox}" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">${inner}</symbol>`,
  );
}

if (missing.length) {
  console.error(`✗ icons not found in lucide-static ${lucideVersion} or icons/brands/: ${missing.join(', ')}`);
  process.exit(1);
}

// stroke-width is set by CSS (.icon { stroke-width: var(--icon-stroke) }) so it can be thin (1.5) to match the line style.
const sprite = `<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">
  <!-- Generated by tools/build-icons.mjs. Do not edit by hand. Lucide v${lucideVersion} (ISC licence, see LICENSE-lucide.txt) + local brand marks. -->
${symbols.join('\n')}
</svg>
`;

await writeFile(path.join(ICON_DIR, 'sprite.svg'), sprite);
await copyFile(path.join(LUCIDE, 'LICENSE'), path.join(ICON_DIR, 'LICENSE-lucide.txt'));
console.log(`✓ sprite.svg: ${symbols.length} icons (lucide-static ${lucideVersion})`);
